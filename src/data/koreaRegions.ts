/** 시·도 / 시·군·구 선택용 (코드는 저장·API용 ASCII 슬러그) */
export type RegionOption = { code: string; name: string }

function pairs(rows: [string, string][]): RegionOption[] {
  return rows.map(([code, name]) => ({ code, name }))
}

