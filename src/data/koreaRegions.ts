export const KOREA_SIGUNGU: Record<string, RegionOption[]> = Object.fromEntries(
  Object.entries(SIGUNGU).map(([k, v]) => [k, pairs(v)]),
) as Record<string, RegionOption[]>

export function getSigunguForSido(sidoCode: string): RegionOption[] {
  return KOREA_SIGUNGU[sidoCode] ?? []
}

/** 예전 데모 값 `gg` → `gyeonggi` */
export function normalizeSidoCode(code: string): string {
  const t = String(code || '').trim()
  if (t === 'gg') return 'gyeonggi'
  return t
}

export function findSidoName(code: string): string {
  const c = normalizeSidoCode(code)
  return KOREA_SIDO.find((s) => s.code === c)?.name ?? code
}

export function findSigunguName(sidoCode: string, sigunguCode: string): string {
  const sido = normalizeSidoCode(sidoCode)
  const hit = getSigunguForSido(sido).find((g) => g.code === sigunguCode)
  return hit?.name ?? sigunguCode
}
